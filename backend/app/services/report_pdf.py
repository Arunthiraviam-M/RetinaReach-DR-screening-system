"""
Generates the clinician-facing PDF report: patient/study info, image
quality status, DR grade + confidence, lesion evidence, Grad-CAM overlay,
and recommendation — everything an ophthalmologist needs to validate in
under 30 seconds, plus the images as they were captured for the record.
"""
from __future__ import annotations

import io
from datetime import datetime

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import (
    Image as RLImage,
    Paragraph,
    SimpleDocTemplate,
    Spacer,
    Table,
    TableStyle,
)

from app.models.patient import Patient
from app.models.study import Study


def _grade_color(grade_value: int):
    return {
        0: colors.HexColor("#16a34a"),
        1: colors.HexColor("#65a30d"),
        2: colors.HexColor("#d97706"),
        3: colors.HexColor("#ea580c"),
        4: colors.HexColor("#dc2626"),
    }.get(grade_value, colors.black)


def build_report_pdf(
    patient: Patient,
    study: Study,
    generated_by_name: str,
    image_paths: dict[str, str | None],
) -> bytes:
    """
    image_paths keys: 'original', 'enhanced', 'gradcam' -> absolute file paths (or None)
    """
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        topMargin=18 * mm,
        bottomMargin=16 * mm,
        leftMargin=16 * mm,
        rightMargin=16 * mm,
        title=f"DR Screening Report - {patient.patient_code}",
    )

    styles = getSampleStyleSheet()
    title_style = ParagraphStyle("TitleCustom", parent=styles["Title"], fontSize=18, spaceAfter=2)
    subtitle_style = ParagraphStyle("Subtitle", parent=styles["Normal"], textColor=colors.HexColor("#475569"))
    h2 = ParagraphStyle("H2Custom", parent=styles["Heading2"], spaceBefore=10, spaceAfter=6)
    body = styles["BodyText"]

    story = []
    story.append(Paragraph("RetinaScan District Screening Report", title_style))
    story.append(Paragraph("Explainable AI-Assisted Diabetic Retinopathy Screening", subtitle_style))
    story.append(Spacer(1, 8))

    grading = study.grading_result
    grade_value = grading.dr_grade.value if grading else -1
    grade_color = _grade_color(grade_value)

    # ---- Patient / study info table ----
    info_data = [
        ["Patient Name", patient.full_name, "Patient ID", patient.patient_code],
        ["Age / Sex", f"{patient.age} / {patient.sex.value.title()}", "District", patient.district or "-"],
        [
            "Diabetes Status",
            patient.diabetes_status.value.replace("_", " ").title(),
            "HbA1c",
            f"{patient.hba1c}%" if patient.hba1c else "Not recorded",
        ],
        [
            "Study Date",
            study.created_at.strftime("%d %b %Y, %I:%M %p"),
            "Report Generated By",
            generated_by_name,
        ],
    ]
    info_table = Table(info_data, colWidths=[38 * mm, 55 * mm, 38 * mm, 55 * mm])
    info_table.setStyle(
        TableStyle(
            [
                ("FONTSIZE", (0, 0), (-1, -1), 9),
                ("FONTNAME", (0, 0), (0, -1), "Helvetica-Bold"),
                ("FONTNAME", (2, 0), (2, -1), "Helvetica-Bold"),
                ("TEXTCOLOR", (0, 0), (0, -1), colors.HexColor("#475569")),
                ("TEXTCOLOR", (2, 0), (2, -1), colors.HexColor("#475569")),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
                ("TOPPADDING", (0, 0), (-1, -1), 5),
                ("LINEBELOW", (0, 0), (-1, -1), 0.4, colors.HexColor("#e2e8f0")),
            ]
        )
    )
    story.append(info_table)
    story.append(Spacer(1, 12))

    # ---- DR Grade banner ----
    if grading:
        grade_data = [
            [
                Paragraph(f"<b>DR Severity: Level {grade_value} — {grading.dr_grade_label}</b>", body),
                Paragraph(
                    f"<b>Referable DR:</b> {'YES' if grading.referable_dr else 'No'}   |   "
                    f"<b>Confidence:</b> {grading.confidence * 100:.0f}%",
                    body,
                ),
            ]
        ]
        grade_table = Table(grade_data, colWidths=[95 * mm, 91 * mm])
        grade_table.setStyle(
            TableStyle(
                [
                    ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#f8fafc")),
                    ("BOX", (0, 0), (-1, -1), 1, grade_color),
                    ("TOPPADDING", (0, 0), (-1, -1), 8),
                    ("BOTTOMPADDING", (0, 0), (-1, -1), 8),
                    ("LEFTPADDING", (0, 0), (-1, -1), 10),
                ]
            )
        )
        story.append(grade_table)
        story.append(Spacer(1, 10))

        story.append(Paragraph("Plain-Language Summary", h2))
        story.append(Paragraph(grading.rationale_summary, body))
        story.append(Spacer(1, 4))
        story.append(Paragraph(grading.rationale_detailed, body))
        story.append(Spacer(1, 8))

        story.append(Paragraph("Lesion-Level Evidence", h2))
        lesion_rows = [["Finding", "Detected", "Est. Count", "Confidence"]]
        for lesion in grading.lesions:
            lesion_rows.append(
                [
                    lesion.lesion_type.replace("_", " ").title(),
                    "Yes" if lesion.detected else "No",
                    str(lesion.count_estimate),
                    f"{lesion.confidence * 100:.0f}%" if lesion.confidence else "-",
                ]
            )
        lesion_table = Table(lesion_rows, colWidths=[55 * mm, 30 * mm, 30 * mm, 30 * mm])
        lesion_table.setStyle(
            TableStyle(
                [
                    ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#0f172a")),
                    ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
                    ("FONTSIZE", (0, 0), (-1, -1), 9),
                    ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#e2e8f0")),
                    ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#f8fafc")]),
                    ("TOPPADDING", (0, 0), (-1, -1), 5),
                    ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
                ]
            )
        )
        story.append(lesion_table)
        story.append(Spacer(1, 10))

        story.append(Paragraph("Recommendation", h2))
        story.append(Paragraph(f"<b>{grading.recommendation}</b>", body))
        story.append(Paragraph(grading.recommendation_reason, body))
        story.append(Paragraph(f"<i>{grading.refer_to}</i>", body))
        story.append(Spacer(1, 10))

    # ---- Images: original / enhanced / Grad-CAM, each shown at 400x300 px ----
    story.append(Paragraph("Captured & Analyzed Images", h2))
    img_flowables = []
    labels = []
    for key, label in [("original", "Original"), ("enhanced", "Enhanced"), ("gradcam", "Grad-CAM")]:
        path = image_paths.get(key)
        if path:
            # 400x300 px at 96dpi ≈ 105.8mm x 79.4mm — scaled down to fit 3-across.
            img_flowables.append(RLImage(path, width=58 * mm, height=43.5 * mm))
            labels.append(Paragraph(f"<para align=center><b>{label}</b></para>", body))

    if img_flowables:
        image_row = Table([img_flowables, labels], colWidths=[60 * mm] * len(img_flowables))
        image_row.setStyle(TableStyle([("ALIGN", (0, 0), (-1, -1), "CENTER")]))
        story.append(image_row)

    story.append(Spacer(1, 14))
    story.append(
        Paragraph(
            f"<font size=8 color='#94a3b8'>Generated by RetinaScan District Screening Platform on "
            f"{datetime.now().strftime('%d %b %Y, %I:%M %p')}. This AI-assisted report is intended to "
            "support, not replace, clinical judgement.</font>",
            body,
        )
    )

    doc.build(story)
    return buffer.getvalue()
